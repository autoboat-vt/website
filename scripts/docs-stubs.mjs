#!/usr/bin/env node

/**
 * Post-build step: materialize a stub `index.html` for every deep docs path.
 *
 * WHY THIS IS NEEDED
 * ------------------
 * `https://autoboat.aoe.vt.edu/documentation/` is a loader page that frames the
 * Cloudflare-hosted docs. That works for the docs HOME, but not for a deep link:
 *
 *     https://autoboat.aoe.vt.edu/documentation/getting_started/setting_up_dev_environment/
 *
 * VT S4 is plain Amazon S3, which returns only an object that exists at that
 * exact key. There is no directory-index fallback, so a deep path is a hard 404
 * unless a real file lives there. (Verified before this script existed: the URL
 * above returned 404 with the SPA's title, meaning S3 served its error document.)
 *
 * So for each path in `src/lib/docsPaths.json` we write a copy of the loader at
 * `dist/documentation/<path>/index.html`. The loader derives which page to frame
 * from its own URL, so one HTML file serves all 63 pages. Cloudflare serves the
 * real content; S3's only job is to return this stub instead of a 404.
 *
 * WHY A MANIFEST INSTEAD OF DERIVING PATHS FROM dist/
 * ---------------------------------------------------
 * The docs pages are NOT part of this repo's build -- they are Markdown in the
 * separate `documentation` repo and are rendered on Cloudflare. `dist/` knows
 * nothing about them, so the path list has to be supplied. It is generated by
 * `scripts/sync-docs-paths.mjs` and committed.
 *
 * WHY NOT A CATCH-ALL (e.g. an `_redirects` splat or a 404.html)
 * --------------------------------------------------------------
 * `public/_redirects` is ignored by S3 (it exists for Netlify-style hosts), and
 * S3's error document is configured VT-side, not by us. Writing real files is
 * the only mechanism available on this host.
 *
 * Run as part of `bun run build`, AFTER `spa-fallback.mjs` (which is what writes
 * `dist/documentation/index.html`, the loader this copies).
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const DIST = join(ROOT, "dist");

const LOADER = join(DIST, "documentation", "index.html");
const MANIFEST = join(ROOT, "src", "lib", "docsPaths.json");

if (!existsSync(LOADER)) {
    // Fail loudly rather than emitting 63 stubs with no template: the whole
    // point is that this file exists in dist/. A missing loader means the build
    // order changed or public/documentation/ was deleted.
    console.error(`docs-stubs: ${LOADER} not found.`);
    console.error("It is produced from public/documentation/index.html by the Vite build.");
    process.exit(1);
}

if (!existsSync(MANIFEST)) {
    console.error(`docs-stubs: ${MANIFEST} not found. Run: node scripts/sync-docs-paths.mjs`);
    process.exit(1);
}

const { pages } = JSON.parse(readFileSync(MANIFEST, "utf8"));
if (!Array.isArray(pages) || pages.length === 0) {
    console.error("docs-stubs: the manifest has no pages.");
    process.exit(1);
}

let written = 0;
for (const page of pages) {
    // The root is already served by dist/documentation/index.html; copying it
    // onto itself would be a no-op at best and is not worth a special case in
    // the manifest, so it is skipped here.
    if (page.path === "/") continue;

    // `path` always starts and ends with "/" (see urlPathFor in
    // sync-docs-paths.mjs). Stripping both ends and re-joining keeps the
    // destination inside dist/documentation/ even if the manifest were
    // hand-edited, so a malformed entry cannot write outside the build.
    const segments = page.path.split("/").filter(Boolean);
    const dest = join(DIST, "documentation", ...segments, "index.html");
    mkdirSync(dirname(dest), { recursive: true });
    copyFileSync(LOADER, dest);
    written++;
}

console.log(`  docs-stubs: wrote ${written} deep-link stubs under dist/documentation/`);
